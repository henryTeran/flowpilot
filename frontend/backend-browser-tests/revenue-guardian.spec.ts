import { expect as baseExpect, test } from "@playwright/test";
import { revenueMoney } from "../src/revenue-utils";
test.use({ timezoneId: "America/Los_Angeles" });
test.setTimeout(90000);
const expect = baseExpect.configure({ timeout: 15000 });
test("native manager billing preserves actual source currencies and refuses corrupted reread", async ({ page, request }, info) => {
  await page.goto("/"); await page.getByLabel("Adresse e-mail").fill("manager@browser.example.com");
  await page.getByLabel("Mot de passe").fill("Browser-test-only-2026");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem("flowpilot.access_token"));
  const params = new URLSearchParams({ start: "2020-01-01T23:00:00Z", end: "2020-01-04T23:00:00Z" });
  const response = await request.get(`http://127.0.0.1:4198/api/v1/revenue/institutes/demo-institute-geneve/billing?${params}`, { headers: { Authorization: `Bearer ${token}` } });
  expect(response.status()).toBe(200); const actual = await response.json(); expect(actual.ticket_count).toBeGreaterThanOrEqual(2);
  let reads = 0, corrupt = false;
  await page.route("**/revenue/institutes/*/billing?**", async route => {
    reads++; const url = new URL(route.request().url());
    expect(url.searchParams.get("start")).toBe("2020-01-01T23:00:00.000Z");
    expect(url.searchParams.get("end")).toBe("2020-01-04T23:00:00.000Z");
    const source = await route.fetch(), value = await source.json(); expect(source.status()).toBe(200);
    if (corrupt) value.settlement_confirmed = true;
    await route.fulfill({ response: source, json: value });
  });
  await page.getByRole("button", { name: "Pilotage", exact: true }).click();
  const panel = page.getByRole("region", { name: "Revenue Guardian", exact: true });
  await expect(panel).toBeVisible(); expect(reads).toBe(0);
  await panel.getByLabel("Date de début").fill("2020-01-02");
  await panel.getByLabel("Date de fin exclue").fill("2020-01-05");
  const button = panel.getByRole("button", { name: "Lire la facturation enregistrée" });
  await button.click(); await expect(panel).toContainText(`${actual.ticket_count} tickets payés dans la période`);
  for (const g of actual.ticket_amounts) if (g.currency && g.known_amount_count) await expect(panel).toContainText(`${revenueMoney(g.known_gross_minor)} ${g.currency}`);
  if (actual.ticket_amounts.some((g: any) => g.currency && !g.known_amount_count)) await expect(panel).toContainText("Aucun montant connu");
  await expect(panel).toContainText(`${actual.tickets_without_active_lines} tickets sans ligne active`);
  corrupt = true; await button.click(); await expect(panel.getByRole("alert")).toBeVisible();
  await expect(panel).not.toContainText("tickets payés dans la période");
  corrupt = false; await button.click(); await expect(panel).toContainText(`${actual.ticket_count} tickets payés dans la période`);
  expect(reads).toBe(3);
  await button.scrollIntoViewIfNeeded(); expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  for (const input of await panel.locator("input").all()) expect((await input.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false);
  await panel.screenshot({ path: info.outputPath("native-revenue-guardian.png") });
});
