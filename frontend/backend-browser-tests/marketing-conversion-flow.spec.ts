import { expect, test } from "@playwright/test";
test("native retained conversion loses reply recovers once retracts and audits actual backend", async ({ page, request }, info) => {
  test.skip(process.env.FLOWPILOT_BROWSER_CONVERSION_FIXTURE !== "1", "Explicit owned conversion fixture required");
  test.setTimeout(120000);
  const api = "http://127.0.0.1:4198", fixture = await (await request.get(api + "/_fixture/conversion")).json();
  fixture.ticket_id = fixture.ticket_ids[info.project.name];
  await page.goto("/"); await page.getByLabel("Adresse e-mail").fill("manager@browser.example.com");
  await page.getByLabel("Mot de passe").fill("Browser-test-only-2026");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem("flowpilot.access_token"));
  const headers = { Authorization: `Bearer ${token}` }, base = `${api}/api/v1/marketing/institutes/${fixture.institute_id}`;
  async function openTicket() {
    await page.getByRole("button", { name: "Marketing", exact: true }).click();
    const marketing = page.getByRole("region", { name: "Marketing", exact: true });
    await expect(marketing.getByRole("button", { name: fixture.label, exact: true })).toBeVisible();
    await marketing.getByRole("button", { name: fixture.label, exact: true }).click();
    await marketing.getByRole("button", { name: "Vérifier les intentions conservées", exact: true }).click();
    await marketing.getByRole("button", { name: "Vérifier les résultats conservés", exact: true }).click();
    const tickets = page.getByRole("region", { name: "Tickets pour conversion", exact: true });
    await tickets.getByLabel("Premier jour de facturation").fill(fixture.start_date);
    await tickets.getByLabel("Dernier jour exclu").fill(fixture.end_date);
    await tickets.getByRole("button", { name: "Lire les tickets payés", exact: true }).click();
    await expect(tickets).toContainText("5 tickets payés");
    await tickets.getByRole("button", { name: new RegExp(`^Ticket ${fixture.ticket_id} ·`) }).click();
  }
  let posts = 0, lose = true, lastKey = "";
  await page.route("**/conversions", async route => {
    if (route.request().method() !== "POST") return route.continue();
    posts++; lastKey = route.request().postDataJSON().idempotency_key;
    const response = await route.fetch(); expect(response.status()).toBe(200);
    if (lose) { lose = false; return route.abort("failed"); }
    return route.fulfill({ response });
  });
  await openTicket();
  const writer = page.getByRole("region", { name: "Enregistrer une conversion", exact: true });
  await writer.getByRole("button", { name: "Vérifier le lien courant", exact: true }).click();
  await expect(writer).toContainText("Aucun lien courant");
  await writer.getByLabel("Motif du lien ou de la rétractation").fill(`Native declared link ${info.project.name}`);
  await writer.getByRole("button", { name: "Enregistrer le lien de conversion", exact: true }).click();
  await expect(writer.getByRole("alert")).toBeVisible(); expect(posts).toBe(1);
  const linked = await (await request.get(`${base}/conversions/original/${lastKey}`, { headers })).json();
  expect(linked.actor_id).toBe("browser-manager"); expect(linked.request.action).toBe("linked");
  await page.reload(); await expect(page.locator(".flow-session-exit")).toBeVisible(); await openTicket();
  await writer.getByRole("button", { name: "Récupérer ou réessayer la même opération", exact: true }).click();
  await expect(writer).toContainText("Lien enregistré"); expect(posts).toBe(1);
  const summary = page.getByRole("region", { name: "Synthèse des conversions", exact: true });
  await summary.getByLabel("Date de début").fill(fixture.start_date);
  await summary.getByLabel("Date de fin exclue").fill(fixture.end_date);
  await summary.getByRole("button", { name: "Lire la synthèse des conversions", exact: true }).click();
  await expect(summary).toContainText("1 tickets liés courants"); await expect(summary).toContainText("123.45 CHF");
  await writer.getByRole("button", { name: "Nouvelle décision pour ce ticket", exact: true }).click();
  await writer.getByRole("button", { name: "Vérifier le lien courant", exact: true }).click();
  await expect(writer).toContainText("Ticket déjà lié");
  await writer.getByLabel("Motif du lien ou de la rétractation").fill(`Native retraction ${info.project.name}`);
  await writer.getByRole("button", { name: "Rétracter le lien courant", exact: true }).click();
  await expect(writer).toContainText("Lien rétracté"); expect(posts).toBe(2);
  await summary.getByRole("button", { name: "Lire la synthèse des conversions", exact: true }).click();
  await expect(summary).toContainText("0 tickets liés courants"); await expect(summary).not.toContainText("123.45 CHF");
  const history = page.getByRole("region", { name: "Historique des conversions", exact: true });
  await history.getByRole("button", { name: "Vérifier l’historique des conversions", exact: true }).click();
  await expect(history).toContainText("Lien courant rétracté"); await expect(history).toContainText("2 décisions conservées");
  await expect(history).toContainText("123.45 CHF");
  const head = await (await request.get(`${base}/conversions/tickets/${fixture.ticket_id}/current`, { headers })).json();
  expect(head.request.expected_previous_id).toBe(linked.id); expect(head.attribution).toEqual(linked.attribution);
  await history.scrollIntoViewIfNeeded(); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("native-conversion-history.png") });
  await summary.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("native-conversion-summary-after-retraction.png") });
});
