import { expect, test } from "@playwright/test";

test("anonymous walk-in proceeds through assignment, extension, finish and recorded cash checkout", async ({ page, request }) => {
  test.setTimeout(60000);
  await page.goto("/");
  await page.getByLabel("Adresse e-mail").fill("manager@browser.example.com");
  await page.getByLabel("Mot de passe").fill("Browser-test-only-2026");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem("flowpilot.access_token"));
  const headers = { Authorization: `Bearer ${token}` };
  // Explicit test-institute catalog denomination; no provider is configured.
  const configured = await request.put("http://127.0.0.1:4198/api/v1/gift-cards/institutes/demo-institute-geneve/settings", { headers, data: { currency: "CHF" } });
  expect(configured.status()).toBe(200);
  await page.getByRole("button", { name: "Je m’identifie", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Angela/ }).click();
  await page.getByRole("button", { name: "Flux tickets", exact: true }).click();
  await page.getByRole("button", { name: /Créer un nouveau ticket/ }).click();
  const arrival = page.getByRole("dialog", { name: "Nouveau Ticket" });
  await arrival.getByRole("button", { name: "Épilation", exact: true }).click();
  await arrival.getByRole("button", { name: /^Aisselles/ }).click();
  const created = page.waitForResponse(response => response.url().endsWith("/api/v1/tickets") && response.request().method() === "POST");
  await arrival.getByRole("button", { name: "Ajouter à la file", exact: true }).click();
  const creation = await created;
  expect(creation.status()).toBe(200);
  const ticket = await creation.json();
  expect(ticket.customer_id).toBeNull();
  expect(ticket.status).toBe("waiting");
  expect(ticket.currency).toBe("CHF");
  const row = page.locator(".bm-ticket-row-clone").filter({ hasText: ticket.ticket_number });
  await row.getByRole("button", { name: "Encaisser / Modifier" }).click();
  await page.locator(".compact-ticket").filter({ hasText: ticket.ticket_number }).click();
  const actions = page.getByRole("dialog").locator(".queue-panel");
  await expect(actions.getByRole("button", { name: "Angela", exact: true })).toBeVisible();
  await actions.getByRole("button", { name: "Angela", exact: true }).click();
  const assigned = page.waitForResponse(response => response.url().endsWith(`/tickets/${ticket.id}/assign`));
  await actions.getByRole("button", { name: "Affecter", exact: true }).click();
  const assignment = await assigned;
  expect(assignment.status()).toBe(200);
  expect((await assignment.json()).assigned_employee_id).toBe("emp-angela");
  const started = page.waitForResponse(response => response.url().endsWith("/planning/sessions/start"));
  await actions.getByRole("button", { name: "Démarrer séance", exact: true }).click();
  expect((await started).status()).toBe(200);
  await page.locator(".drawer-close-button").click();
  const session = page.locator(".session-block").filter({ hasText: "Aisselles" });
  await expect(session).toBeVisible();
  const extended = page.waitForResponse(response => response.url().endsWith("/extend"));
  await session.getByRole("button", { name: "+5", exact: true }).click();
  expect((await extended).status()).toBe(200);
  const finished = page.waitForResponse(response => response.url().endsWith("/finish"));
  await session.getByRole("button", { name: "Fin + caisse", exact: true }).click();
  expect((await finished).status()).toBe(200);
  const checkout = page.locator(".bm-checkout-clone");
  await expect(checkout).toBeVisible();
  await checkout.getByRole("button", { name: "esp.", exact: true }).click();
  const paid = page.waitForResponse(response => response.url().endsWith(`/tickets/${ticket.id}/checkout/pay`));
  await checkout.getByRole("button", { name: "Enregistrer le paiement", exact: true }).click();
  const payment = await paid;
  expect(payment.status()).toBe(200);
  const receipt = await payment.json();
  expect(receipt.status).toBe("paid");
  expect(receipt.payment_method).toBe("especes");
  expect(receipt.paid_employee_id).toBe("emp-angela");
  expect(receipt.lines[0].performed_by_employee_id).toBe("emp-angela");
  const cashflows = await request.get("http://127.0.0.1:4198/api/v1/payments/institutes/demo-institute-geneve/cashflows", { headers });
  expect((await cashflows.json()).accounts).toEqual([]); // Internal cash entry is not provider settlement.
});
