import { expect, test } from "@playwright/test";

test("native orders and measured partial receipts recover committed originals and update stock once", async ({ page, request }, info) => {
  const exceptions: string[] = []; page.on("pageerror", error => exceptions.push(error.message));
  await page.goto("/");
  await page.getByLabel("Adresse e-mail").fill("manager@browser.example.com");
  await page.getByLabel("Mot de passe").fill("Browser-test-only-2026");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem("flowpilot.access_token"));
  const headers = { Authorization: `Bearer ${token}` }, api = "http://127.0.0.1:4198/api/v1/inventory/institutes/demo-institute-geneve";
  const supplierReply = await request.post(`${api}/suppliers`, { headers, data: { reference: `PO-SUP-${info.project.name}`, name: `Achats ${info.project.name}`, reason: "Fournisseur de livraison contrôlée", idempotency_key: `po-supplier-${info.project.name}` } });
  expect(supplierReply.status()).toBe(200); const supplier = await supplierReply.json();
  const itemReply = await request.post(`${api}/items`, { headers, data: { sku: `PO-${info.project.name}`, name: `Serum achat ${info.project.name}`, category: "cabine", unit: "ml", reorder_threshold: "1.000", reason: "Article de livraison contrôlée", idempotency_key: `po-item-${info.project.name}` } });
  expect(itemReply.status()).toBe(200); const item = await itemReply.json();
  await page.getByRole("button", { name: "Inventaire", exact: true }).click();
  const stockDetail = page.getByRole("region", { name: "Article de stock", exact: true });
  await page.locator(".bm-stock-card").filter({ hasText: item.sku }).click();
  await expect(stockDetail).toContainText("Stock enregistré : 0,000 ml");
  await page.getByRole("button", { name: "Commandes", exact: true }).click();
  const orders = page.getByRole("region", { name: "Commandes de l’institut" });
  const create = orders.getByRole("form", { name: "Créer une commande", exact: true });
  await create.getByLabel("Choisir le fournisseur").selectOption(supplier.id);
  await create.getByLabel("Référence de commande").fill(`PO-REF-${info.project.name}`);
  await create.getByLabel("Article à ajouter").selectOption(item.id);
  await create.getByRole("button", { name: "Ajouter à la commande", exact: true }).click();
  await create.getByLabel(`Quantité commandée pour ${item.name} (ml)`).fill("10,125");
  await create.getByLabel("Motif de commande").fill("Réapprovisionnement mesuré institut");
  let originalOrder: any;
  await page.route(`${api}/orders`, async route => { if (route.request().method() !== "POST") return route.continue(); const result = await route.fetch(); expect(result.status()).toBe(200); originalOrder = await result.json(); await route.abort("failed"); }, { times: 1 });
  await create.getByRole("button", { name: "Enregistrer la commande", exact: true }).click();
  await expect(create.getByRole("alert")).toBeVisible();
  await page.reload(); await page.getByRole("button", { name: "Inventaire", exact: true }).click();
  await page.locator(".bm-stock-card").filter({ hasText: item.sku }).click();
  await expect(stockDetail).toContainText("Stock enregistré : 0,000 ml");
  await page.getByRole("button", { name: "Commandes", exact: true }).click();
  await expect(create).toContainText("10,125 ml");
  const orderReplay = page.waitForResponse(response => response.url() === `${api}/orders` && response.request().method() === "POST");
  await create.getByRole("button", { name: "Reprendre la demande originale", exact: true }).click();
  expect(await (await orderReplay).json()).toEqual(originalOrder);
  const detail = orders.getByRole("region", { name: "Détail de commande" });
  await expect(detail).toContainText("À recevoir");
  expect((await (await request.get(`${api}/items/${item.id}`, { headers })).json()).on_hand).toBe("0.000");
  const receive = detail.getByRole("form", { name: "Recevoir une livraison", exact: true });
  await expect(receive.getByLabel(`Quantité reçue pour ${item.name} (ml)`)).toHaveValue("");
  await receive.getByLabel(`Quantité reçue pour ${item.name} (ml)`).fill("2,125");
  await receive.getByLabel("Motif de réception").fill("Première livraison comptée");
  let originalReceipt: any;
  const receiptPath = `${api}/orders/${originalOrder.id}/receipts`;
  await page.route(receiptPath, async route => { if (route.request().method() !== "POST") return route.continue(); const result = await route.fetch(); expect(result.status()).toBe(200); originalReceipt = await result.json(); await route.abort("failed"); }, { times: 1 });
  await receive.getByRole("button", { name: "Confirmer la réception", exact: true }).click();
  await expect(receive.getByRole("alert")).toBeVisible();
  await expect(page.locator(".bm-stock-card").filter({ hasText: item.sku })).toHaveCount(0);
  await expect(stockDetail).not.toContainText("Stock enregistré :");
  await page.reload(); await page.getByRole("button", { name: "Inventaire", exact: true }).click();
  await page.locator(".bm-stock-card").filter({ hasText: item.sku }).click();
  await expect(stockDetail).toContainText("Stock enregistré : 2,125 ml");
  await page.getByRole("button", { name: "Commandes", exact: true }).click();
  await orders.getByRole("button", { name: `Reprendre la réception de ${originalOrder.reference}`, exact: true }).click();
  const receiptReplay = page.waitForResponse(response => response.url() === receiptPath && response.request().method() === "POST");
  await receive.getByRole("button", { name: "Reprendre la demande originale", exact: true }).click();
  expect(await (await receiptReplay).json()).toEqual(originalReceipt);
  await expect(receive.getByRole("status")).toContainText("Réception enregistrée");
  await expect(detail).toContainText("Réception partielle"); await expect(detail.getByRole("table")).toContainText("8,000 ml");
  await expect(page.locator(".bm-stock-card").filter({ hasText: item.sku })).toContainText("2,125 ml");
  await expect(stockDetail).toContainText("Stock enregistré : 2,125 ml"); await expect(stockDetail.locator("li")).toHaveCount(1);
  expect(await (await request.get(receiptPath, { headers })).json()).toEqual([originalReceipt]);
  expect(await (await request.get(`${api}/items/${item.id}/movements`, { headers })).json()).toHaveLength(1);
  await receive.getByLabel(`Quantité reçue pour ${item.name} (ml)`).fill("8"); await receive.getByLabel("Motif de réception").fill("Solde livraison compté");
  await receive.getByRole("button", { name: "Confirmer la réception", exact: true }).click();
  await expect(detail).toContainText("Entièrement reçue"); await expect(detail.getByRole("table")).toContainText("0,000 ml");
  await expect(receive.getByRole("button", { name: "Confirmer la réception", exact: true })).toBeDisabled();
  await expect(page.locator(".bm-stock-card").filter({ hasText: item.sku })).toContainText("10,125 ml");
  await expect(stockDetail).toContainText("Stock enregistré : 10,125 ml"); await expect(stockDetail.locator("li")).toHaveCount(2);
  expect(await (await request.get(receiptPath, { headers })).json()).toHaveLength(2);
  expect(await (await request.get(`${api}/items/${item.id}/movements`, { headers })).json()).toHaveLength(2);
  expect(await (await request.get(`${api}/orders/${originalOrder.id}`, { headers })).json()).toEqual(originalOrder);
  expect(await page.evaluate(() => Object.keys(sessionStorage).filter(key => key.startsWith("flowpilot.purchase-request:")).length)).toBe(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false); expect(exceptions).toEqual([]);
  await detail.screenshot({ path: info.outputPath("purchase-order-receipts.png") });
});
