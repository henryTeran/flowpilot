import { expect, test } from "@playwright/test";

test("native unpaid correction retains original execution after lost reply and payment", async ({ page, request }, info) => {
  test.setTimeout(60000);
  await page.goto("/");
  await page.getByLabel("Adresse e-mail").fill("manager@browser.example.com");
  await page.getByLabel("Mot de passe").fill("Browser-test-only-2026");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  const token = await page.evaluate(() => sessionStorage.getItem("flowpilot.access_token"));
  const headers = { Authorization: `Bearer ${token}` }, api = "http://127.0.0.1:4198/api/v1", institute = "demo-institute-geneve";
  expect((await request.put(`${api}/gift-cards/institutes/${institute}/settings`, { headers, data: { currency: "CHF" } })).status()).toBe(200);
  const created = await request.post(`${api}/tickets`, { headers, data: { institute_id: institute, service_ids: ["svc-aisselles", "svc-aisselles"] } });
  expect(created.status()).toBe(200); const ticket = await created.json();
  const started = await request.post(`${api}/planning/sessions/start`, { headers, data: { ticket_id: ticket.id, employee_id: "emp-angela", service_id: "svc-aisselles" } });
  expect(started.status()).toBe(200); const execution = await started.json();
  const basisPath = `${api}/inventory/institutes/${institute}/executions/sessions/${execution.id}/basis`;
  const original = await (await request.get(basisPath, { headers })).json();
  expect(original.entries).toHaveLength(2);
  await page.getByRole("button", { name: "Je m’identifie", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Angela/ }).click();
  const session = page.locator(`.session-block[data-session-id="${execution.id}"]`);
  await expect(session).toBeVisible();
  const finished = page.waitForResponse(response => response.url().endsWith(`/sessions/${execution.id}/finish`));
  await session.getByRole("button", { name: "Fin + caisse", exact: true }).click();
  expect((await finished).status()).toBe(200);
  const checkout = page.locator(".bm-checkout-clone");
  await expect(checkout.locator(".bm-cash-line-item")).toHaveCount(2);
  const line = ticket.lines.find((row: any) => row.id === execution.ticket_line_id);
  const path = `${api}/tickets/${ticket.id}/checkout/lines/${line.id}/remove`;
  let committed: any;
  await page.route(path, async route => {
    const reply = await route.fetch(); expect(reply.status()).toBe(200);
    committed = await reply.json(); await route.abort("failed");
  }, { times: 1 });
  const index = [...ticket.lines].sort((a: any, b: any) => a.id.localeCompare(b.id)).findIndex((row: any) => row.id === line.id);
  await checkout.locator(".bm-cash-line-item").nth(index).getByTitle("Retirer cette prestation", { exact: true }).click();
  await expect.poll(() => !!committed).toBe(true);
  expect(committed.lines).toHaveLength(1); expect(committed.removed_lines).toHaveLength(1);
  expect((await (await request.patch(path, { headers })).json()).removed_lines).toEqual(committed.removed_lines);
  await page.reload();
  await expect(page.locator(".flow-session-exit")).toBeVisible();
  await page.getByRole("button", { name: "Je m’identifie", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Angela/ }).click();
  await page.getByRole("button", { name: "Flux tickets", exact: true }).click();
  await page.locator(".bm-ticket-row-clone").filter({ hasText: ticket.ticket_number }).getByRole("button", { name: "Encaisser / Modifier" }).click();
  await expect(checkout.locator(".bm-cash-line-item")).toHaveCount(1);
  const retained = page.getByRole("region", { name: "Prestations retirées de la facture" });
  await expect(retained).toContainText("browser-manager");
  await retained.screenshot({ path: info.outputPath("invoice-correction.png") });
  expect(await (await request.get(basisPath, { headers })).json()).toEqual(original);
  await checkout.getByRole("button", { name: "esp.", exact: true }).click();
  const payment = page.waitForResponse(response => response.url().endsWith(`/tickets/${ticket.id}/checkout/pay`));
  await checkout.getByRole("button", { name: "Enregistrer le paiement", exact: true }).click();
  const paid = await payment; expect(paid.status()).toBe(200); const receipt = await paid.json();
  expect(receipt.total_amount).toBe(ticket.total_amount - line.total);
  expect(receipt.removed_lines).toEqual(committed.removed_lines);
  expect(await (await request.patch(path, { headers })).json()).toEqual(receipt);
  await expect.poll(async () => await checkout.count() ? await checkout.getAttribute("data-ticket-id") : null).not.toBe(ticket.id);
  if (await checkout.count()) await checkout.getByRole("button", { name: "Retour", exact: true }).click();
  await expect(checkout).not.toBeVisible();
  await page.getByRole("button", { name: "Inventaire", exact: true }).click();
  const work = page.getByRole("region", { name: "Consommations par prestation" });
  await work.locator(".bm-stock-card").filter({ hasText: ticket.ticket_number }).filter({ hasText: "Retirée de la facture" }).click();
  const billing = work.getByRole("region", { name: "Lien de facturation" });
  await expect(billing).toContainText("Retirée de la facture");
  await expect(billing).toContainText("ne détermine pas les quantités réellement utilisées");
  const consumption = work.getByRole("form", { name: "Confirmer la consommation" });
  await expect(consumption.locator("input[inputmode='decimal']")).toHaveCount(0);
  await expect(consumption.locator("input[type='checkbox']")).not.toBeChecked();
  await billing.screenshot({ path: info.outputPath("invoice-consumption-context.png") });
});
